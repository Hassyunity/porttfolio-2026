-- Agent IA piloté depuis /admin (à exécuter dans Supabase > SQL Editor, après blog_posts.sql).
-- Idempotent : peut être relancé sans risque.
--
-- agent_scripts : consignes enregistrées (réutilisables).
-- agent_runs    : chaque exécution d'une consigne, mise à jour par le workflow GitHub Actions
--                 (.github/workflows/ai-agent.yml) avec la clé service_role.

-- --- Scripts -----------------------------------------------------------------
create table if not exists public.agent_scripts (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(btrim(title)) between 1 and 200),
  prompt text not null default '' check (char_length(prompt) <= 20000),
  -- Dépôt GitHub cible, au format propriétaire/nom.
  repo text not null check (repo ~ '^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$'),
  -- Branche de départ ; vide = branche par défaut du dépôt.
  base_branch text not null default '' check (char_length(base_branch) <= 200),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create or replace function public.agent_scripts_touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists agent_scripts_touch_updated_at on public.agent_scripts;
create trigger agent_scripts_touch_updated_at
  before update on public.agent_scripts
  for each row execute function public.agent_scripts_touch_updated_at();

-- --- Exécutions --------------------------------------------------------------
create table if not exists public.agent_runs (
  id bigint generated by default as identity primary key,
  script_id bigint not null references public.agent_scripts (id) on delete cascade,
  -- Copie de la consigne au lancement : modifier le script ne change pas une exécution en cours.
  prompt text not null,
  repo text not null,
  base_branch text not null default '',
  status text not null default 'queued'
    check (status in ('queued', 'running', 'succeeded', 'failed', 'cancelled')),
  branch text,
  pr_url text,
  run_url text,
  gh_run_id bigint,
  -- Compte rendu de l'agent (Markdown) et message d'erreur éventuel.
  result text,
  error text,
  cost_usd numeric(10, 4),
  created_at timestamptz not null default now(),
  started_at timestamptz,
  finished_at timestamptz
);

create index if not exists agent_runs_script_idx on public.agent_runs (script_id, created_at desc);

-- --- Sécurité (RLS) : administrateurs uniquement -----------------------------
alter table public.agent_scripts enable row level security;
alter table public.agent_runs enable row level security;

drop policy if exists "Gestion des scripts par les admins" on public.agent_scripts;
create policy "Gestion des scripts par les admins"
  on public.agent_scripts for all
  to authenticated
  using (public.is_blog_admin())
  with check (public.is_blog_admin());

drop policy if exists "Gestion des exécutions par les admins" on public.agent_runs;
create policy "Gestion des exécutions par les admins"
  on public.agent_runs for all
  to authenticated
  using (public.is_blog_admin())
  with check (public.is_blog_admin());

revoke all on public.agent_scripts, public.agent_runs from anon;
grant select, insert, update, delete on public.agent_scripts, public.agent_runs to authenticated;
