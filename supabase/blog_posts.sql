-- Articles du blog gérés depuis /admin (à exécuter dans Supabase > SQL Editor).
-- Idempotent : peut être relancé sans risque.
--
-- Après exécution :
--   1. Authentication > Users > "Add user" > "Create new user" : votre email + mot de passe
--      (cochez "Auto Confirm User").
--   2. Authentication > Sign In / Providers > Email : désactivez "Allow new users to sign up".
--   3. Donnez-vous les droits d'admin (remplacez l'email) :
--        insert into public.blog_admins (user_id)
--        select id from auth.users where email = 'votre@email.com'
--        on conflict do nothing;

-- --- Administrateurs ---------------------------------------------------------
create table if not exists public.blog_admins (
  user_id uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);

-- Aucune policy : la table n'est lisible que via la fonction ci-dessous.
alter table public.blog_admins enable row level security;

create or replace function public.is_blog_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (select 1 from public.blog_admins where user_id = auth.uid());
$$;

revoke all on function public.is_blog_admin() from public;
grant execute on function public.is_blog_admin() to anon, authenticated;

-- --- Articles ----------------------------------------------------------------
-- Les identifiants démarrent à 1000 pour ne pas croiser ceux des articles
-- historiques (JSON, id 1 à 3) qui partagent la table des commentaires.
create table if not exists public.blog_posts (
  id bigint generated by default as identity (start with 1000) primary key,
  slug text not null unique
    check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' and char_length(slug) <= 120),
  title text not null check (char_length(btrim(title)) between 1 and 200),
  excerpt text not null default '' check (char_length(excerpt) <= 500),
  content text not null default '' check (char_length(content) <= 100000),
  tags text[] not null default '{}' check (cardinality(tags) <= 8),
  status text not null default 'draft' check (status in ('draft', 'published')),
  -- Date de mise en ligne : dans le futur = article programmé.
  published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint blog_posts_published_has_date check (status = 'draft' or published_at is not null)
);

create index if not exists blog_posts_public_idx
  on public.blog_posts (published_at desc)
  where status = 'published';

create or replace function public.blog_posts_touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists blog_posts_touch_updated_at on public.blog_posts;
create trigger blog_posts_touch_updated_at
  before update on public.blog_posts
  for each row execute function public.blog_posts_touch_updated_at();

-- --- Sécurité (RLS) ----------------------------------------------------------
alter table public.blog_posts enable row level security;

-- Visiteurs : uniquement les articles publiés dont la date est passée.
-- Brouillons et articles programmés restent invisibles, même via l'API.
drop policy if exists "Lecture publique des articles publiés" on public.blog_posts;
create policy "Lecture publique des articles publiés"
  on public.blog_posts for select
  to anon, authenticated
  using (status = 'published' and published_at <= now());

-- Administrateurs : accès complet.
drop policy if exists "Gestion complète par les admins" on public.blog_posts;
create policy "Gestion complète par les admins"
  on public.blog_posts for all
  to authenticated
  using (public.is_blog_admin())
  with check (public.is_blog_admin());

grant select on public.blog_posts to anon;
grant select, insert, update, delete on public.blog_posts to authenticated;
